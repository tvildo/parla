// worklet_bundle.ts — the engine worklet (src/engine/js/worklet.ts, as emitted JavaScript in build/js/) and its imports
// as ONE classic script (Node built-ins only). Used by src/extension/build.ts and the SDK builds: the bundle loads as an
// AudioWorklet module, from a blob, or with importScripts() in a worker, so it can't rely on ES module imports.
import fs from 'node:fs';
import path from 'node:path';

/** where `python build.py ts` (tsc) writes the browser code: build/js/<same path>.js */
export const emitted = (repo: string, ...rel: string[]): string => {
  const f = path.join(repo, 'build', 'js', ...rel).replace(/\.ts$/, '.js');
  if (!fs.existsSync(f)) throw new Error(`missing ${f} (run: python build.py ts)`);
  return f;
};

/** ES modules -> one classic script: each module becomes a scope returning its exports; imports become
 *  destructuring of those scopes. Enough for our own small, acyclic module graph. */
export function bundle(entry: string, { repo, by }: { repo: string; by: string }): string {
  const done = new Map<string, null>();
  const order: string[] = [];
  const varOf = (f: string) => `__vi_${path.basename(f, '.js').replace(/\W/g, '_')}`;
  function visit(file: string) {
    if (done.has(file)) return;
    done.set(file, null);
    let src = fs.readFileSync(file, 'utf8');
    const imports: string[] = [];
    src = src.replace(/^\s*import\s*\{([^}]*)\}\s*from\s*'(\.\/[^']+)';?\s*$/gm, (_, names: string, rel: string) => {
      const dep = path.resolve(path.dirname(file), rel);
      imports.push(dep);
      return `const {${names}} = ${varOf(dep)};`;
    });
    if (/^\s*import\s/m.test(src)) throw new Error(`${file}: unsupported import form`);
    const exported: string[] = [];
    src = src.replace(/^export\s+(const|let|function|class|async function)\s+([A-Za-z_$][\w$]*)/gm, (_, kw: string, name: string) => { exported.push(name); return `${kw} ${name}`; });
    src = src.replace(/^export \{\};\s*$/m, '');   // tsc's marker for a module without exports
    if (/^export\s/m.test(src)) throw new Error(`${file}: unsupported export form`);
    for (const d of imports) visit(d);
    order.push(`// ---- ${path.relative(repo, file).replace(/\\/g, '/')}\nconst ${varOf(file)} = (() => {\n${src}\nreturn { ${exported.join(', ')} };\n})();\n`);
  }
  visit(entry);
  const from = path.relative(path.join(repo, 'build', 'js'), entry).replace(/\\/g, '/').replace(/\.js$/, '.ts');
  return `// GENERATED by ${by} from ${from} and its imports. Do not edit.\n${order.join('\n')}`;
}

/** The SDK's code as emitted, into `dir`: parla, react (and assets unless the caller writes its own), vi_engine (the engine
 *  glue under the SDK's name), each .js + .d.ts. Declarations keep the `.ts` specifiers they were written with (tsc
 *  rewrites only the JavaScript): those become `.js`, which TypeScript maps to the .d.ts next to it. */
/** a release build's version (CI: the next semantic tag, docs/releasing.md) in the SDK code copied by sdkCode */
export function stampVersion(dir: string, version: string): void {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`--version X.Y.Z, not ${version}`);
  for (const [f, re, to] of [
    ['parla.js', /export const VERSION = '[^']*'/, `export const VERSION = '${version}'`],
    ['parla.d.ts', /export declare const VERSION = "[^"]*"/, `export declare const VERSION = "${version}"`],
  ] as const) {
    const p = path.join(dir, f), s = fs.readFileSync(p, 'utf8');
    if (!re.test(s)) throw new Error(`${p}: no VERSION to stamp`);
    fs.writeFileSync(p, s.replace(re, to));
  }
}

export function sdkCode(repo: string, dir: string, { assets = true } = {}): void {
  fs.mkdirSync(dir, { recursive: true });
  const dts = (s: string) => s.replace(/(from\s+'\.\.?\/[^']+)\.ts'/g, "$1.js'");
  const files: [string, string][] = [['src/sdk/src/parla', 'parla'], ['src/sdk/src/react', 'react'], ['src/engine/js/vi_engine', 'vi_engine']];
  if (assets) files.push(['src/sdk/src/assets', 'assets']);
  for (const [src, name] of files) {
    fs.copyFileSync(emitted(repo, `${src}.ts`), path.join(dir, `${name}.js`));
    fs.writeFileSync(path.join(dir, `${name}.d.ts`), dts(fs.readFileSync(emitted(repo, `${src}.ts`).replace(/\.js$/, '.d.ts'), 'utf8')));
  }
}

/** NOTICE + the licence text of every model package shipped: what has to travel with the weights */
export function notices(repo: string, models: string[]): string {
  const parts = [fs.readFileSync(path.join(repo, 'NOTICE'), 'utf8').trimEnd()];
  for (const m of models) {
    const f = path.join(repo, 'models', m, 'LICENSE');
    if (fs.existsSync(f)) parts.push(`==== models/${m}/LICENSE ====\n\n${fs.readFileSync(f, 'utf8').trimEnd()}`);
  }
  return parts.join('\n\n') + '\n';
}

/** a classic script (content script, worker, worklet) as emitted: tsc marks every file a module (`export {};`) */
export function classic(file: string): string {
  const src = fs.readFileSync(file, 'utf8').replace(/^export \{\};\s*$/m, '');
  if (/^\s*(import|export)\s/m.test(src)) throw new Error(`${file}: a classic script can't import or export`);
  return src;
}
