// npm.ts — the npm package @tvildo/parla (Node built-ins only).
//
//   node src/sdk/npm.ts [--wasm build/wasm] [--out build/npm] [--pack] [--version X.Y.Z (a release: the next tag)]
//
// The package carries the engine's files (engine/: worklet bundle + 3 wasm builds; models/: the three quality levels)
// and points at them with `new URL('./…', import.meta.url)` (dist/assets.js, generated here): bundlers (Vite, webpack 5,
// Rollup, esbuild, Parcel) emit each file as an asset, so `Parla.load()` needs no `base` in a bundled app. Only the
// files of the model in use are downloaded by the browser.
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { bundle, emitted, notices, sdkCode, stampVersion } from '../../tools/worklet_bundle.ts';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SDK = path.join(REPO, 'src', 'sdk');
const args = process.argv.slice(2);
const arg = (n: string, d: string) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };
const OUT = path.resolve(REPO, arg('out', 'build/npm'));
const WASM = path.resolve(REPO, arg('wasm', 'build/wasm'));
const MODELS = ['deepfilternet3', 'rnnoise', 'gtcrn'];
const BUILDS = ['relaxed', 'simd', 'nosimd'];
const sourceVersion = JSON.parse(fs.readFileSync(path.join(SDK, 'package.json'), 'utf8')).version;
const version = arg('version', '') || sourceVersion;
// parla.ts exports VERSION too: one number everywhere
const codeVersion = /export const VERSION = '([^']+)'/.exec(fs.readFileSync(path.join(SDK, 'src', 'parla.ts'), 'utf8'))?.[1];
if (codeVersion !== sourceVersion) throw new Error(`src/sdk/src/parla.ts VERSION ${codeVersion} != src/sdk/package.json ${sourceVersion}`);

fs.rmSync(OUT, { recursive: true, force: true });
const dist = path.join(OUT, 'dist');
fs.mkdirSync(path.join(dist, 'engine'), { recursive: true });

// code (assets.js is written below: the package's own files)
sdkCode(REPO, dist, { assets: false });
if (version !== sourceVersion) stampVersion(dist, version);
fs.writeFileSync(path.join(dist, 'engine', 'worklet.bundle.js'), bundle(emitted(REPO, 'src', 'engine', 'js', 'worklet.ts'), { repo: REPO, by: 'src/sdk/npm.ts' }));

// engine + models
const files = ['engine/worklet.bundle.js'];
for (const b of BUILDS) {
  const f = path.join(WASM, `vi_rs_${b}.wasm`);
  if (!fs.existsSync(f)) throw new Error(`missing ${f} (python build.py wasm)`);
  fs.copyFileSync(f, path.join(dist, 'engine', `vi_rs_${b}.wasm`));
  files.push(`engine/vi_rs_${b}.wasm`);
}
const notice = ['@tvildo/parla (Apache-2.0). The model packages keep their own licences:', ''];
for (const m of MODELS) {
  const src = path.join(REPO, 'models', m);
  fs.mkdirSync(path.join(dist, 'models', m), { recursive: true });
  const man = JSON.parse(fs.readFileSync(path.join(src, 'manifest.json'), 'utf8'));
  if (fs.existsSync(path.join(src, 'LICENSE'))) fs.copyFileSync(path.join(src, 'LICENSE'), path.join(dist, 'models', m, 'LICENSE'));
  for (const f of ['manifest.json', man.graph, man.weights].filter(Boolean)) {
    fs.copyFileSync(path.join(src, f), path.join(dist, 'models', m, f));
    files.push(`models/${m}/${f}`);
  }
  notice.push(`${m}: ${man.license || 'see the package'}${man.source ? ` (${man.source})` : ''}`);
}
// one literal `new URL()` per file: bundlers only follow static strings
fs.writeFileSync(path.join(dist, 'assets.js'), [
  '// GENERATED by src/sdk/npm.ts: the package\'s files as URLs the bundler resolves (each becomes an asset).',
  'export const ASSETS = {',
  ...files.map((f) => `  ${JSON.stringify(f)}: new URL(${JSON.stringify(`./${f}`)}, import.meta.url),`),
  '};',
  '',
].join('\n'));
fs.copyFileSync(path.join(REPO, 'LICENSE'), path.join(OUT, 'LICENSE'));
fs.writeFileSync(path.join(OUT, 'NOTICE'), notices(REPO, MODELS) + '\n' + notice.join('\n') + '\n');
fs.copyFileSync(path.join(SDK, 'README.npm.md'), path.join(OUT, 'README.md'));

fs.writeFileSync(path.join(OUT, 'package.json'), JSON.stringify({
  name: '@tvildo/parla',
  version,
  description: 'AI noise suppression for a web app\'s microphone, on the user\'s device (WebAssembly + AudioWorklet). React hook included.',
  license: 'Apache-2.0',
  author: 'tvildo (https://github.com/tvildo)',
  homepage: 'https://parla.cc',
  repository: { type: 'git', url: 'git+https://github.com/tvildo/parla.git', directory: 'src/sdk' },
  bugs: 'https://github.com/tvildo/parla/issues',
  keywords: ['noise-suppression', 'noise-cancellation', 'webrtc', 'audio', 'microphone', 'wasm', 'audioworklet', 'react', 'speech'],
  type: 'module',
  main: './dist/parla.js',
  types: './dist/parla.d.ts',
  exports: {
    '.': { types: './dist/parla.d.ts', default: './dist/parla.js' },
    './react': { types: './dist/react.d.ts', default: './dist/react.js' },
    './package.json': './package.json',
  },
  // TypeScript with moduleResolution "node" (node10) ignores `exports`: point it at the subpath's types too
  typesVersions: { '*': { react: ['./dist/react.d.ts'] } },
  sideEffects: false,
  files: ['dist', 'NOTICE'],
  peerDependencies: { react: '>=18' },
  peerDependenciesMeta: { react: { optional: true } },
  publishConfig: { access: 'public' },
}, null, 2) + '\n');

let bytes = 0;
(function walk(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else bytes += fs.statSync(p).size; } })(OUT);
console.log(`@tvildo/parla ${version} -> ${OUT} (${(bytes / 1e6).toFixed(1)} MB, ${files.length} engine/model files)`);
if (args.includes('--pack')) {
  // constant arguments only (no path in the command string): the .tgz goes next to OUT
  const out = execSync('npm pack --pack-destination ..', { cwd: OUT, encoding: 'utf8' }).trim().split('\n').pop() ?? '';
  console.log(`pack -> ${path.join(path.dirname(OUT), out)}`);
  // the same file under a fixed name: examples/ install it whatever the version (a release stamps a new one)
  fs.copyFileSync(path.join(path.dirname(OUT), out), path.join(path.dirname(OUT), 'tvildo-parla.tgz'));
}
